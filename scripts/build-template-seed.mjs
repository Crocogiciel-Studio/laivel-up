#!/usr/bin/env node
// Generates supabase/migrations/<ts>_seed_templates.sql -- the five read-only
// templates (#61): the AIDD reference grid and the four sample profiles, as
// `is_template = true` rows with a fixed id each. Re-run after changing
// presets/aidd.json or test/fixtures/profiles/*; commit the regenerated .sql.
//
//   pnpm build && node scripts/build-template-seed.mjs
//
// The migration is idempotent (ON CONFLICT (id) DO UPDATE), so db:push / a
// local db reset keep the templates in step with the repo sources.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { readProfileFromDirectory } from '../dist/adapters/inbound/json-profile.js';
import { parseGrid, parseProfile } from '../dist/compose.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const OUT = resolve(ROOT, 'supabase/migrations/20260901000000_seed_templates.sql');

// Fixed ids: idempotent upsert, and a stable target for "clone from template".
const GRID_ID = '61111111-0000-4000-8000-000000000001';
const PROFILES = [
  { dir: 'perceval', id: '61111111-0000-4000-8000-000000000011', name: 'Perceval' },
  { dir: 'bohort', id: '61111111-0000-4000-8000-000000000012', name: 'Bohort' },
  { dir: 'leodagan', id: '61111111-0000-4000-8000-000000000013', name: 'Léodagan' },
  { dir: 'arthur', id: '61111111-0000-4000-8000-000000000014', name: 'Arthur' },
];

const sqlString = (value) => `'${JSON.stringify(value).replace(/'/g, "''")}'`;

// --- grid ---------------------------------------------------------------------
const gridBody = JSON.parse(readFileSync(resolve(ROOT, 'presets/aidd.json'), 'utf8'));
const gridCheck = parseGrid(gridBody);
if (!gridCheck.ok) throw new Error(`presets/aidd.json does not parse: ${gridCheck.error.message}`);

// --- profiles ---------------------------------------------------------------
const profileRows = PROFILES.map(({ dir, id, name }) => {
  const read = readProfileFromDirectory(resolve(ROOT, 'test/fixtures/profiles', dir));
  if (!read.ok) throw new Error(`profile ${dir}: ${read.error.message}`);
  const body = JSON.parse(JSON.stringify(read.value));
  const check = parseProfile(body);
  if (!check.ok) throw new Error(`profile ${dir} body does not round-trip: ${check.error.message}`);
  return { id, name, body };
});

// --- emit ------------------------------------------------------------------
const lines = [
  '-- #61: the known references as read-only templates (org_id NULL, is_template).',
  '-- GENERATED by scripts/build-template-seed.mjs from presets/aidd.json and',
  '-- test/fixtures/profiles/* -- edit those and re-run, do not hand-edit this file.',
  '-- Idempotent: fixed ids + ON CONFLICT DO UPDATE keep the rows current on every',
  '-- db:push and local db reset.',
  '',
  'insert into public.grid (id, org_id, created_by, name, body, is_template) values',
  `  ('${GRID_ID}', null, null, 'AIDD reference', ${sqlString(gridBody)}::jsonb, true)`,
  'on conflict (id) do update set name = excluded.name, body = excluded.body, updated_at = now();',
  '',
  'insert into public.profile (id, org_id, created_by, name, body, is_template) values',
  profileRows
    .map((r) => `  ('${r.id}', null, null, '${r.name}', ${sqlString(r.body)}::jsonb, true)`)
    .join(',\n'),
  'on conflict (id) do update set name = excluded.name, body = excluded.body, updated_at = now();',
  '',
];

writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}`);
console.log(`  grid: AIDD reference (${GRID_ID})`);
for (const r of profileRows) console.log(`  profile: ${r.name} (${r.id})`);
